import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => localStorage.setItem('kartenstudio.tipps.v1', '1'));
const p = await ctx.newPage();
p.on('pageerror', e => console.log('ERR', e)); p.on('console', m => m.type()==='error' && console.log('C', m.text()));
await p.goto('http://localhost:4173/#ort=pottenstein'); 
await p.waitForSelector('#landing', { state: 'hidden', timeout: 60000 });
await p.waitForTimeout(1500);
await p.click('#wzStyles button[data-p="vintage"]'); await p.waitForTimeout(500);
await p.locator('#fxRelief').scrollIntoViewIfNeeded();
await p.check('#fxRelief'); await p.waitForSelector('#relief', { timeout: 30000 }).catch(()=>console.log('kein relief'));
await p.waitForTimeout(800);
await p.screenshot({ path: 'test-results/r4-relief.png' });
await p.click('#wzStyles button[data-p="dunkel"]'); await p.waitForTimeout(300);
await p.check('#fxSchatten');
await p.fill('#fxKipp', '50'); await p.dispatchEvent('#fxKipp', 'change'); await p.waitForTimeout(1500);
await p.screenshot({ path: 'test-results/r4-kipp-dunkel.png' });
await b.close();
